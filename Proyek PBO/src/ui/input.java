    private void submit_buttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submit_buttonActionPerformed
        String judul = judul_field.getText();
        String deskripsi = deskripsi_field.getText();
        String kategori = "";
        
        if (makananCB.isSelected()){
            kategori = "Makanan & Minuman";
        } 
        else if (belanjaCB.isSelected()){
            kategori = "Belanja";
        }
        else{
            kategori = "Lainnya";
        }
        
        int jumlahPengeluaran = Integer.parseInt(jumlah_field.getText());

        LocalDate tanggal = LocalDate.now();
        String tgl = tanggal.toString(); 
        
        Pengeluaran pengeluaran = new Pengeluaran(judul, deskripsi, kategori, jumlahPengeluaran, tgl);
        
        String query = "INSERT INTO pengeluaran (judul, deskripsi, tipe_pengeluaran, uang_keluar, tanggal, username) " +
               "VALUES ('" + judul + "', '" + deskripsi + "', '" + kategori + "', " + jumlahPengeluaran + ", '" + tgl + "', '" + this.user.getUsername() + "')";

        Connector conn = new Connector();
        if (conn.executeUpdate(query)){
            JOptionPane.showMessageDialog(null, "Data berhasil dimasukkan!", "Success", JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(null, "Gagal memasukkan data! "+JOptionPane.ERROR_MESSAGE, "Error", JOptionPane.ERROR_MESSAGE);

        }

        dashboard db = new dashboard();
        db.setUser(this.user);
        db.setVisible(true);
        db.setSize(330, 545);
        
        this.dispose();
        
    }//GEN-LAST:event_submit_buttonActionPerformed

