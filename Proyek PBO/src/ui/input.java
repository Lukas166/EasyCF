    private void judul_fieldFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_judul_fieldFocusLost
        if (judul_field.getText().equals("")){
            judul_field.setText("  Masukkan judul");
            judul_field.setForeground(new Color(153, 153, 153));
            judul_field.setFont(new Font("Segoe UI", Font.ITALIC, 13));
        }
    }//GEN-LAST:event_judul_fieldFocusLost

    private void judul_fieldFocusGained(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_judul_fieldFocusGained
        if (judul_field.getText().equals("  Masukkan judul")){
            judul_field.setText("");
            judul_field.setForeground(new Color(255, 255, 255));
            judul_field.setFont(new Font("Segoe UI", Font.PLAIN, 13));
        }
    }//GEN-LAST:event_judul_fieldFocusGained

